// Post-build: write out/sw.js, the offline service worker for the static export.
// It precaches every file the export emits (hashed bundles, fonts, workers, the
// worklet, LAME, icons) under a version derived from their contents, so a new
// deploy installs a new cache and drops the old one. The orb video (~2 MB, only a
// fallback for weak GPUs) is cached on first use instead of up front.
// Audio never passes through it: sources are read from local files and masters are
// blob: URLs, neither of which a service worker sees.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

/** Files never precached: the worker itself, source maps, and large optional media. */
const SKIP = [/^sw\.js$/, /\.map$/, /^media\/.*\.mp4$/];

function walk(dir, root = dir) {
  return readdirSync(dir).flatMap(name => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path, root) : [relative(root, path).split(sep).join('/')];
  });
}

/**
 * The URLs to precache for an export directory, sorted; `index.html` is served as `/`.
 * @param {string} root
 * @returns {string[]}
 */
export function precacheList(root) {
  return walk(root)
    .filter(file => !SKIP.some(re => re.test(file)))
    .map(file => (file === 'index.html' ? '/' : `/${file}`))
    .sort();
}

/**
 * Cache version: a hash over every precached file's path and contents.
 * @param {string} root
 * @param {string[]} urls
 */
export function cacheVersion(root, urls) {
  const hash = createHash('sha256');
  for (const url of urls) {
    hash.update(url);
    hash.update(readFileSync(join(root, url === '/' ? 'index.html' : url.slice(1))));
  }
  return hash.digest('hex').slice(0, 16);
}

/** The service worker source. */
export function serviceWorker(version, urls) {
  return `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = 'xyp3rn-${version}';
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(key => key.startsWith('xyp3rn-') && key !== CACHE).map(key => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // Media range requests (the orb video) go straight to the network.
  if (request.headers.has('range')) return;
  // Pages: network first so a new deploy is picked up; the cached app when offline.
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('/', { cacheName: CACHE })));
    return;
  }
  // Everything else is static and content-hashed: cache first, then network (and keep it).
  event.respondWith(
    caches.match(request, { cacheName: CACHE }).then(hit => hit || fetch(request).then(response => {
      if (response.status === 200 && response.type === 'basic') {
        const copy = response.clone();
        caches.open(CACHE).then(cache => cache.put(request, copy));
      }
      return response;
    })),
  );
});
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = process.argv[2] ?? 'out';
  const urls = precacheList(root);
  const version = cacheVersion(root, urls);
  writeFileSync(join(root, 'sw.js'), serviceWorker(version, urls));
  console.log(`sw.js: ${urls.length} files precached, version ${version}`);
}
